"""Настройки сервиса — все в одном файле.

Критерий воспроизводимости требует, чтобы эксперт запустил решение без правок
кода. Значит любое значение, которое может понадобиться поменять при запуске,
должно читаться из переменной окружения и иметь разумное значение по умолчанию,
а не лежать константой посреди обработчика.
"""
from __future__ import annotations

import os
from pathlib import Path

# Корень репозитория. Считаем от файла, а не от текущей директории: сервис
# запускают и через `python -m src.api`, и из docker с другим cwd.
ROOT = Path(__file__).resolve().parents[2]


def _env_path(name: str, default: Path) -> Path:
    raw = os.getenv(name)
    return Path(raw).expanduser().resolve() if raw else default


def _env_int(name: str, default: int) -> int:
    try:
        return int(os.getenv(name, ""))
    except ValueError:
        return default


# --------------------------------------------------------------------------------------
# Пути
# --------------------------------------------------------------------------------------

DATA_DIR = _env_path("FENOLOG_DATA_DIR", ROOT / "data")

# Сохранённые полигоны. Один JSON-файл вместо базы: полигонов десятки, а не
# миллионы, зато состояние видно глазами и переживает перезапуск контейнера,
# если каталог data/ смонтирован томом.
POLYGONS_FILE = DATA_DIR / "polygons.json"

# Собранный фронтенд. Если каталога нет — сервис всё равно поднимается и отдаёт
# только API: незачем ронять бэкенд из-за несобранного интерфейса.
WEB_DIST = _env_path("FENOLOG_WEB_DIST", ROOT / "web" / "dist")

MODELS_DIR = ROOT / "models"

# --------------------------------------------------------------------------------------
# Сбор данных
# --------------------------------------------------------------------------------------

# Сколько сезонов истории тянем по умолчанию. Ядру для собственной климатической
# нормы нужно минимум три года; пять — компромисс между качеством нормы и
# временем ожидания на демонстрации.
DEFAULT_YEARS = _env_int("FENOLOG_YEARS", 5)
MAX_YEARS = _env_int("FENOLOG_MAX_YEARS", 16)

# Потолок числа сцен на один анализ. Ограничение существует ради времени ответа:
# без него плотная история Sentinel-2 по крупному полю тянется минутами, и показ
# на защите превращается в ожидание. None — тянуть всё, что нашлось.
MAX_SCENES = _env_int("FENOLOG_MAX_SCENES", 220)

# --------------------------------------------------------------------------------------
# Фоновые задачи
# --------------------------------------------------------------------------------------

# Сколько анализов идёт одновременно. Сбор упирается в сеть, а не в процессор,
# поэтому потоков больше, чем ядер. Больше четырёх нет смысла: внешние источники
# начинают отвечать 429.
TASK_WORKERS = _env_int("FENOLOG_TASK_WORKERS", 4)

# Сколько держим завершённую задачу в памяти, прежде чем забыть её результат.
TASK_TTL_SECONDS = _env_int("FENOLOG_TASK_TTL", 3600)

# --------------------------------------------------------------------------------------
# Состояние источников
# --------------------------------------------------------------------------------------

# Проверка живости источников сама ходит в сеть и занимает секунды. Держим
# результат недолгое время, иначе индикатор в интерфейсе станет тормозить
# страницу при каждом обновлении.
HEALTH_TTL_SECONDS = _env_int("FENOLOG_HEALTH_TTL", 60)

# Обязательный заголовок для Nominatim и Overpass: правила OSM требуют
# опознаваемого имени приложения, безымянные запросы отбиваются с 403.
USER_AGENT = "fenolog/1.0 (vegetation monitoring service)"
