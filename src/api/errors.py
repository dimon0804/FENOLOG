"""Страницы ошибок сервиса и правило выбора между HTML и JSON.

Сервис выходит на публичный домен, а значит на него будут попадать не только
через интерфейс: по старой ссылке, по опечатке в адресе, из поисковика, во
время перезапуска. Стандартный ответ Starlette в таких случаях — строка
`Not Found` на белом фоне; для публичного сервиса это выглядит как поломка.

Файлы страниц лежат рядом, в `error_pages/`, а не в `web/public/`, и это
осознанный выбор. Всё, что кладётся в `web/public/`, попадает наружу только
после `npm run build`; страница ошибки, доступная лишь при удачной сборке
фронтенда, бесполезна ровно в тех случаях, ради которых она написана (сборки
нет, каталог `dist` не смонтирован, интерфейс не собрался). Здесь же они —
часть питоновского пакета: едут в образ вместе с кодом и работают всегда.
Побочная выгода: их нет в корне `dist`, и StaticFiles не подменяет ими
машинные ответы API — про это ниже.

Один и тот же адрес обязан отвечать по-разному в зависимости от того, кто
спрашивает. Браузеру человека нужна страница, интерфейсу — JSON с полем
`detail`: весь фронтенд разбирает ошибки именно так, и HTML вместо JSON он
показал бы как «неизвестная ошибка».

Отдельных страниц для 502 и 504 нет намеренно. Их не может выдать само
приложение — они рождаются на обратном прокси, когда до приложения не
достучались или оно не ответило вовремя. Для посетителя это то же самое
событие, что и 503: сервис сейчас не отвечает, надо повторить через несколько
минут. Разные тексты про «шлюз» и «таймаут» ничего ему не дают, а различать
их нужно администратору — и он видит это в логе прокси, а не на странице.
Поэтому на прокси все три кода указывают на один файл:

    error_page 502 503 504 /503.html;
"""
from __future__ import annotations

from http import HTTPStatus
from pathlib import Path

from fastapi import Request
from fastapi.responses import HTMLResponse, JSONResponse, Response

PAGES_DIR = Path(__file__).resolve().parent / "error_pages"

# Готовые страницы. Для кодов не из этого списка HTML не рисуется: наружу они
# не выходят, а плодить почти одинаковые файлы ради полноты незачем.
_FILES = {404: "404.html", 500: "500.html", 503: "503.html"}

# Короткие формулировки для машинного ответа. Тот же смысл, что на странице,
# но без подробностей: JSON читает интерфейс, а не человек.
_DETAILS = {
    404: "Не найдено",
    500: "Внутренняя ошибка сервиса",
    503: "Сервис временно недоступен",
}

# Страницы читаются с диска один раз. Они маленькие и не меняются на ходу, а
# обращение к диску в обработчике ошибки — лишняя точка отказа в момент, когда
# уже что-то сломалось.
_cache: dict[int, str] = {}


def page_html(status: int) -> str | None:
    """Разметка страницы по коду ответа или None, если своей страницы нет."""
    if status in _cache:
        return _cache[status]
    name = _FILES.get(status)
    if name is None:
        return None
    path = PAGES_DIR / name
    try:
        html = path.read_text(encoding="utf-8")
    except OSError:
        # Файл не доехал в образ — не повод отвечать пятисотой на пятисотую.
        # Вызывающий откатится на JSON.
        return None
    _cache[status] = html
    return html


def wants_json(request: Request) -> bool:
    """Кому отвечаем машинно, а кому страницей.

    Решает в первую очередь адрес, а не заголовок Accept: под `/api` и
    `/health` живёт только машинный контракт, и отдать туда HTML нельзя даже
    браузеру с открытой вкладкой — иначе `fetch` в интерфейсе споткнётся о
    разбор ответа, а `/health` перестанет годиться для docker healthcheck.

    Для остальных адресов смотрим Accept. Браузер при переходе по ссылке
    просит `text/html` и получает страницу; `fetch`, `curl` и любой клиент со
    звёздочкой в Accept получают JSON — им страница не нужна.
    """
    path = request.url.path
    if path.startswith("/api") or path == "/health":
        return True
    return "text/html" not in request.headers.get("accept", "")


def _detail(status: int, detail: str | None) -> str:
    """Пояснение к машинному ответу.

    Своё сообщение обработчика («Участок не найден») дороже любого общего и
    отдаётся как есть. Но когда его нет, Starlette подставляет английское
    название кода — `Not Found`; в сервисе, который весь по-русски, оно
    выглядит как чужая строка, попавшая в ответ по недосмотру. Английские
    заготовки узнаём по совпадению со стандартной формулировкой и меняем на
    свои.
    """
    if detail:
        try:
            standard = HTTPStatus(status).phrase
        except ValueError:
            standard = None
        if detail != standard:
            return detail
    return _DETAILS.get(status, "Ошибка")


def error_response(
    request: Request,
    status: int,
    detail: str | None = None,
    headers: dict[str, str] | None = None,
) -> Response:
    """Ответ об ошибке в том виде, который поймёт конкретный клиент."""
    if not wants_json(request):
        html = page_html(status)
        if html is not None:
            return HTMLResponse(content=html, status_code=status, headers=headers)
    return JSONResponse(
        status_code=status,
        content={"detail": _detail(status, detail)},
        headers=headers,
    )
