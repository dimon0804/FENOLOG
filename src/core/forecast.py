"""Прогноз развития поля до конца сезона.

Заказчик просит не только разбор прошлого, но и ответ на вопрос «что будет к
уборке». Ответ нужен банку и страховой, поэтому он обязан быть не красивым, а
измеримым: каждое число ниже подобрано на ретроспективной проверке по
data/train_dataset.csv (39 полигонов, сезоны 2010-2024, 2 108 срезов,
35 933 пары «прогноз - факт»), а не выбрано на глаз.

Схема прогноза
--------------
Нейросети здесь неоткуда взяться и они запрещены условиями кейса, да и не нужны:
форма сезонной кривой уже известна из истории самого поля — это климатическая
норма по дню года. Вперёд переносится не сам индекс, а ОТКЛОНЕНИЕ от нормы,
затухающее со временем:

    ndvi(t0 + k) = норма(t0 + k) + d0 · exp(-k / TAU)

где d0 — текущее отклонение от нормы, k — дни вперёд.

Смысл модели простой и агрономически честный: поле, просевшее сегодня,
просевшим и останется завтра, но к концу горизонта разница либо отыграется,
либо размоется — и лучшей догадкой снова становится норма.

Почему именно затухание, а не «останется как есть»
--------------------------------------------------
Скорость затухания измерена напрямую. Для каждого среза бралось стартовое
отклонение d0, и фактическое отклонение через k дней регрессировалось на него:
коэффициент показывает, какая доля отклонения дожила до дня k.

    дни вперёд    1-7    8-14   15-21  22-30  31-45  46-60
    доля дожила   0.77   0.66   0.50   0.31   0.06   -0.05

Это и есть экспонента с характерным временем около 20 дней. Крайние значения
важнее середины: у отклонения NDVI от нормы память примерно в три недели, а
после сорока дней текущее состояние поля не несёт о будущем НИКАКОЙ информации —
коэффициент садится на ноль и уходит в минус. Отсюда два следствия, которые
заложены в модуль:

* на горизонте 60 дней точечный прогноз почти совпадает с нормой, и это не
  дефект модели, а свойство данных;
* риск поэтому считается не по одной последней точке горизонта, а по среднему
  отклонению за весь горизонт — величине, которая реально предсказуема
  (корреляция прогноза с фактом 0.51) и которая ближе к тому, что нужно
  страховщику: накопленный за период недобор вегетации.

Что даёт проверка
-----------------
Замер прогоном самой forecast_season (а не прототипа) на 2 010 ретроспективных
срезах: срез = поле + сезон + дата обрезки из 140/170/200/230 дня года, история
подаётся с прошлого сезона — ровно в том виде, в каком её собирает analyze().
Сравнение идёт с ФАКТИЧЕСКИМИ наблюдениями после среза, а не с восстановленным
рядом, 34 925 пар «прогноз - факт».

    горизонт      прогноз   «останется как сейчас»   «просто норма»    пар
    до 7 дней     0.0947          0.1140                 0.1488        3 825
    8-14 дней     0.0992          0.1359                 0.1384        4 270
    15-30 дней    0.1229          0.1911                 0.1378        9 339
    31-60 дней    0.1250          0.2670                 0.1241       17 491
    весь 1-60     0.1185          0.2217                 0.1325       34 925

Прогноз обгоняет оба наивных варианта на всех горизонтах до 30 дней: минус 17 %
ошибки против «останется как сейчас» на первой неделе и минус 36 % против него
же на 15-30 днях, минус 36 % против нормы на первой неделе. На 31-60 днях он
сравнивается с нормой (0.1250 против 0.1241) — ровно потому, что к этому сроку
в норму и превращается. Хуже наивных вариантов он не бывает нигде.

Границы применимости — то, чего этот прогноз не умеет
-----------------------------------------------------
* Горизонт полезного знания — около 30 дней. Дальше прогноз честно вырождается
  в климатическую норму, и продавать его как «предсказание поля на два месяца»
  нельзя: это предсказание СЕЗОНА, к которому добавлен затухающий след
  сегодняшнего состояния.
* Погода в прогноз не входит вообще. Засуха, которая начнётся завтра, модели
  неизвестна — она увидит её только постфактум, когда та отразится в NDVI.
  Это же и главное направление развития: прогноз осадков и температуры на
  горизонт есть в открытых источниках, и он способен сдвинуть траекторию.
* Уборка не предсказывается. Резкий обвал индекса при уборке или гибели посева
  выглядит для модели как отклонение и переносится вперёд затухающим следом,
  тогда как физически поле уже не вернётся. Периоды с таким обвалом ядро метит
  причиной CAUSE_ABRUPT — интерфейсу стоит показывать это рядом с прогнозом.
* Проверка сделана на 39 полях одного региона с историей 2010-2024. На поле без
  собственной истории (норма по культуре) прогноз не проверялся ни разу:
  в обучающем наборе таких полей нет. Уверенность там снижена намеренно.
* Севооборот прогноз не знает. Если в этом сезоне на поле другая культура,
  норма описывает чужую кривую, и отклонение будет систематическим, а не
  случайным. Признак беды — устойчиво большой |z| весь сезон.
* Риск оценивается по среднему отклонению за горизонт, а не по урожайности.
  Связь NDVI с урожаем в этом наборе не проверялась, потому что урожайности в
  нём нет; заявлять «минус 30 процентов к уборке» в центнерах прогноз права
  не имеет — только «минус 30 процентов вегетации к норме».
"""
from __future__ import annotations

from datetime import date, timedelta

import numpy as np

# Идентификатор метода в ответе. Меняется только вместе со схемой прогноза.
METHOD = "climatology_anchored"

# --------------------------------------------------------------------------
# Константы модели. Все три подобраны перебором на ретроспективе, таблицы
# перебора — в docstring соответствующих констант.
# --------------------------------------------------------------------------

# Характерное время затухания отклонения, дни.
# Перебор при окне 5 дней (общий RMSE на горизонте 1-60):
#     tau     10      15      20      25      30      40      60      inf
#     RMSE  0.1318  0.1292  0.1287  0.1295  0.1311  0.1351  0.1434  0.2211
# Минимум пологий и приходится на 18-22; берём 20. Крайние точки перебора — это
# ровно два наивных варианта: tau -> 0 даёт «просто норму», tau -> inf даёт
# «останется как сейчас». То есть модель честно лежит между ними, а перебор
# показывает, что оптимум внутри, а не на границе.
DECAY_TAU_DAYS = 20.0

# Окно усреднения текущего отклонения, дни.
# Перебор (общий RMSE, tau = 20):
#     окно     3       5       7      10      14      21      28      45
#     RMSE  0.1282  0.1287  0.1292  0.1300  0.1316  0.1353  0.1417
# Данные требуют окна короче, чем подсказывает интуиция «две-три недели», и
# причина не в том, что берётся одна свежая точка: на вход подаётся уже
# сглаженный Уиттекером ряд, каждое значение которого само собрано по
# наблюдениям за ±2 недели. Эффективное усреднение как раз двухнедельное,
# а окно поверх него нужно лишь для устойчивости к хвосту сглаживания.
# Взято 5, а не оптимальные 3: разница 0.0005 RMSE, зато втрое меньше вес
# у последней точки сетки, которая держится всего на одном-двух снимках.
ANOMALY_WINDOW_DAYS = 5

# Ширина интервала: sigma(k) = (SIGMA_A + SIGMA_B * sqrt(k)) * масштаб поля.
# Коэффициенты — МНК-подгонка по фактической ошибке прогноза, разбитой на бины
# горизонта (замер на 34 925 парах «прогноз - факт»):
#     k        1-2     3-4     5-7    8-10   11-14   15-21   22-30   31-45   46-60
#     RMSE   0.0758  0.0763  0.1069  0.0947  0.1028  0.1214  0.1239  0.1247  0.1253
# Корень из k, а не линейный рост: ошибка быстро растёт в первые две недели и
# выходит на полку.
SIGMA_A = 0.0721
SIGMA_B = 0.01059

# Горизонт, после которого ширина интервала перестаёт расти.
# Видно прямо в таблице выше: с 22-30 дней RMSE встаёт на 0.124 и дальше не
# меняется (0.1239 -> 0.1247 -> 0.1253). Причина содержательная: к этому сроку
# отклонение затухло, прогноз сравнялся с нормой, и его ошибка — это уже просто
# разброс поля вокруг собственной нормы, который от горизонта не зависит.
# Без насыщения интервал на дальнем конце раздувается, и покрытие уезжает
# с 0.80 до 0.86 — интервал перестаёт быть 80-процентным и становится 86-.
#     насыщение после   25 дн   30 дн   35 дн   45 дн   без насыщения
#     покрытие всего    0.803   0.812   0.817   0.824      0.827
#     бин 31-60 дней    0.814   0.828   0.839   0.853      0.860
SIGMA_SATURATION_DAYS = 25.0

# Масштаб интервала по конкретному полю. Ошибка прогноза прямо зависит от того,
# насколько само поле разболтано: разбивка по квартилям разброса нормы даёт
#     clim_std 0.050-0.087 -> RMSE 0.0850
#     clim_std 0.087-0.114 -> RMSE 0.0877
#     clim_std 0.114-0.168 -> RMSE 0.1377
#     clim_std 0.168-0.241 -> RMSE 0.1802
# то есть двукратная разница. Интервал поэтому растягивается пропорционально
# разбросу нормы поля относительно типового значения 0.125. Подрезка нужна,
# чтобы поле с вырожденной нормой не получило ни неправдоподобно узкий, ни
# бесконечно широкий интервал.
SIGMA_REF_STD = 0.125
SIGMA_SCALE_MIN, SIGMA_SCALE_MAX = 0.6, 1.6

# Множитель полуширины интервала для заявленных 80 %.
# Итоговое измеренное покрытие (доля фактических наблюдений между low и high,
# замер прогоном самой forecast_season по 2 010 срезам):
#     весь горизонт 1-60 дней   0.803
#     до 7 дней                 0.799
#     8-14 дней                 0.793
#     15-30 дней                0.790
#     31-60 дней                0.814
# Нормальный квантиль дал бы 1.282, но остатки тяжелохвостые: реальный множитель
# для 80 % меньше теоретического, и берётся он из замера, а не из таблицы.
INTERVAL_Z = 1.10
INTERVAL_LEVEL = 0.80

# Пороги риска по среднему за горизонт отклонению от нормы, в долях.
# Проверка на ретроспективе (n = 2 108 срезов, факт — среднее фактическое
# отклонение за тот же горизонт):
#     прогноз            n     факт (медиана)   доля факт < -15 %   доля факт z < -1
#     низкий  > -7 %   1 475       +4.9 %             0.17               0.02
#     умеренный -7..-20 %  481    -15.7 %             0.52               0.11
#     высокий < -20 %    152      -32.2 %             0.74               0.26
# Пороги не круглые числа с потолка: прогнозное отклонение оказалось практически
# несмещённым — по бинам медиана факта попадает в тот же бин
# (прогноз -20..-12 % -> факт -18.9 %, прогноз -12..-7 % -> факт -12.9 %).
# Порог -7 % отделяет то, что уже не тонет в шуме одного наблюдения (0.066 NDVI
# при типовой норме около 0.5), порог -20 % примерно соответствует минус одной
# сигме нормы, то есть границе класса «угнетение биомассы» из contracts.py.
RISK_MODERATE_DEVIATION = -0.07
RISK_HIGH_DEVIATION = -0.20

RISK_LOW = "low"
RISK_MODERATE = "moderate"
RISK_HIGH = "high"

# Уверенность. Ошибка 0.30 NDVI — это отклонение, при котором прогноз перестаёт
# что-либо значить: типовая амплитуда сезонной кривой около 0.5, промах в 0.3
# путает всходы с уборкой. Ожидаемая ошибка на конце горизонта делится на эту
# величину, и получается доля «сколько от полного незнания мы отыграли».
CONFIDENCE_FULL_ERROR = 0.30

# Штраф за несвежие данные. Замерено отдельным прогоном: наблюдения искусственно
# обрезались за N дней до среза, всё остальное без изменений.
#     задержка   0 дн   7 дн   14 дн   21 дн   28 дн
#     RMSE      0.1172 0.1240 0.1370  0.1430  0.1564
#     рост       1.00   1.06   1.17    1.22    1.34
# Рост близок к линейному — примерно 1.2 % ошибки на каждый день молчания.
STALENESS_PENALTY_PER_DAY = 0.012

# Штраф за норму по типу культуры вместо собственной истории поля. Прямо
# измерить на обучающем наборе нельзя (там у всех полей своя история), поэтому
# число взято из уже измеренного в проекте: RMSE между кривыми двух полей одной
# культуры 0.108 против собственного шума наблюдения 0.066, то есть такая норма
# добавляет примерно столько же ошибки, сколько всё остальное вместе.
CROP_NORM_CONFIDENCE = 0.75

# Пороги истории поля. Три сезона — минимум, при котором норма вообще считается
# (MIN_REFERENCE_YEARS в climatology.py); восемь — уровень, начиная с которого
# добавление ещё одного года почти не двигает норму.
YEARS_TRUSTED = 8
YEARS_MINIMAL = 3

# Потолок длины прогноза. Дальше 120 дней от последнего снимка выдавать что-либо
# нельзя: это уже следующая культура в севообороте, а не это поле.
MAX_FORECAST_DAYS = 120

_MONTHS_GENITIVE = (
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)


def forecast_season(
    dates: list[date],
    restored: np.ndarray,
    clim_mean: np.ndarray,
    clim_std: np.ndarray,
    crop_type: str | None = None,
    horizon_days: int = 60,
    today: date | None = None,
    *,
    n_reference_years: int | None = None,
    clim_source: str = "polygon",
    last_observation: date | None = None,
) -> dict:
    """Прогноз развития поля вперёд от последней даты ряда.

    Параметры
    ---------
    dates, restored
        Посуточный восстановленный ряд NDVI — то, что уже собрало ядро.
    clim_mean, clim_std
        Климатическая норма и её разброс на тех же датах. Норма вперёд берётся
        из этих же массивов по дню года: сезонная кривая повторяется, и ничего
        сверх уже посчитанного ядром модулю не нужно.
    crop_type
        Культура. На саму траекторию не влияет (форму задаёт норма поля),
        используется только в формулировке для агронома.
    horizon_days
        На сколько дней вперёд от сегодняшнего дня нужен прогноз.
    today
        Подставляется в тестах, чтобы результат не зависел от календаря.
        Если сегодня позже конца ряда, прогноз всё равно строится от конца ряда,
        но продлевается так, чтобы покрыть horizon_days вперёд ОТ СЕГОДНЯ.

    Дополнительные именованные параметры (все необязательные, вызов по основной
    сигнатуре работает без них) нужны только для оценки уверенности:
    n_reference_years — сколько сезонов под нормой, clim_source — "polygon" или
    "crop", last_observation — дата последнего реального снимка.

    Возвращает
    ----------
    Словарь с полями dates / ndvi / low / high / clim / method / horizon_days /
    confidence / expected_deviation / risk / summary. Списки одинаковой длины,
    первая дата — следующий день после конца ряда.

    Дополнительно в словаре лежат поля, которые полезны интерфейсу, но в
    обязательный контракт не входят: anchor_date, stale_days, interval_level,
    expected_deviation_mean (среднее отклонение за весь горизонт — именно по
    нему определяется риск), current_deviation.
    """
    dates = list(dates)
    restored = np.asarray(restored, dtype=float)
    clim_mean = np.asarray(clim_mean, dtype=float)
    clim_std = np.asarray(clim_std, dtype=float)

    n = len(dates)
    if n == 0 or restored.size != n or clim_mean.size != n or clim_std.size != n:
        return _empty("ряд пуст или массивы разной длины", horizon_days)

    anchor = dates[-1]
    today = today or anchor
    # Ряд может кончаться раньше сегодняшнего дня — облачность или конец сезона
    # съёмки. Прогноз всё равно строится от конца ряда: свежее опоры у нас нет.
    stale_days = max((today - anchor).days, 0)
    horizon_days = max(int(horizon_days), 1)
    n_days = min(horizon_days + stale_days, MAX_FORECAST_DAYS)
    # Если запрошенный горизонт упёрся в потолок, наружу отдаётся то, что
    # действительно посчитано, а не то, что просили: интерфейс не должен
    # подписывать график сроком, которого в нём нет.
    horizon_days = max(n_days - stale_days, 1)

    f_dates = [anchor + timedelta(days=k) for k in range(1, n_days + 1)]
    f_clim_mean, f_clim_std = _norm_forward(dates, clim_mean, clim_std, f_dates)

    k = np.arange(1, n_days + 1, dtype=float)
    decay = np.exp(-k / DECAY_TAU_DAYS)

    # Текущее отклонение от нормы: среднее по последним ANOMALY_WINDOW_DAYS дням
    # ряда. Именно оно, а не сам уровень NDVI, переносится вперёд.
    dev_hist = restored - clim_mean
    tail = dev_hist[-ANOMALY_WINDOW_DAYS:]
    tail = tail[np.isfinite(tail)]
    have_norm = bool(np.isfinite(f_clim_mean).any()) and tail.size > 0
    d0 = float(tail.mean()) if tail.size else 0.0

    if have_norm:
        ndvi = f_clim_mean + d0 * decay
    else:
        # Нормы нет вовсе (поле без истории и без нормы по культуре). Затухать
        # некуда, и единственное защитимое утверждение — «останется как сейчас».
        # Это заведомо слабый прогноз, поэтому уверенность ниже добивается до
        # минимума, а интервал остаётся широким.
        ndvi = np.full(n_days, float(restored[-1]))
        f_clim_mean = np.full(n_days, np.nan)
        f_clim_std = np.full(n_days, np.nan)

    # NDVI физически ограничен. Норма плюс отклонение изредка вылезает за
    # границы — например, когда поле убрано раньше срока и уходит к голой почве.
    ndvi = np.clip(ndvi, -0.2, 1.0)

    sigma = _interval_sigma(k, f_clim_std)
    half = INTERVAL_Z * sigma
    low = np.clip(ndvi - half, -0.2, 1.0)
    high = np.clip(ndvi + half, -0.2, 1.0)

    # --- отклонение от нормы: в конце горизонта и в среднем за горизонт -------
    # Конец горизонта считается не по одной последней точке, а по последней
    # неделе: единственный день на конце сетки — это уже чистая экстраполяция
    # нормы, и опираться на него в отчёте банку нельзя.
    if have_norm:
        base_end = float(np.nanmean(f_clim_mean[-7:]))
        dev_end = float(np.nanmean(ndvi[-7:] - f_clim_mean[-7:]))
        expected_deviation = dev_end / max(base_end, 0.05)
        base_all = float(np.nanmean(f_clim_mean))
        dev_all = float(np.nanmean(ndvi - f_clim_mean))
        deviation_mean = dev_all / max(base_all, 0.05)
    else:
        expected_deviation = 0.0
        deviation_mean = 0.0

    # Риск — по среднему отклонению за весь горизонт. Отклонение в самой
    # последней точке для этого не годится: на 60 днях оно затухает почти в
    # ноль, и любой прогноз оказался бы «низким риском». Проверка это
    # подтвердила: по конечной точке в категорию выше «низкой» не попадал ни
    # один срез из 2 108, а по среднему за горизонт разделение работает и
    # согласуется с фактом.
    risk = _risk_of(deviation_mean if have_norm else 0.0)

    confidence = _confidence(
        n_days=n_days,
        f_clim_std=f_clim_std,
        have_norm=have_norm,
        stale_days=stale_days,
        n_reference_years=n_reference_years,
        clim_source=clim_source,
        last_observation=last_observation,
        anchor=anchor,
    )

    summary = _summary(
        f_dates[-1],
        deviation_mean=deviation_mean,
        deviation_end=expected_deviation,
        risk=risk,
        confidence=confidence,
        have_norm=have_norm,
        stale_days=stale_days,
        crop_type=crop_type,
        clim_source=clim_source,
    )

    return {
        "dates": [d.isoformat() for d in f_dates],
        "ndvi": [round(float(v), 4) for v in ndvi],
        "low": [round(float(v), 4) for v in low],
        "high": [round(float(v), 4) for v in high],
        "clim": [None if not np.isfinite(v) else round(float(v), 4) for v in f_clim_mean],
        "method": METHOD,
        "horizon_days": horizon_days,
        "confidence": round(float(confidence), 3),
        "expected_deviation": round(float(expected_deviation), 4),
        "risk": risk,
        "summary": summary,
        # --- сверх обязательного контракта, для интерфейса и отладки ---
        "anchor_date": anchor.isoformat(),
        "stale_days": stale_days,
        "interval_level": INTERVAL_LEVEL,
        "expected_deviation_mean": round(float(deviation_mean), 4),
        "current_deviation": round(float(d0), 4),
        "decay_tau_days": DECAY_TAU_DAYS,
    }


