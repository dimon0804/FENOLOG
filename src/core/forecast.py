def _norm_forward(
    dates: list[date],
    clim_mean: np.ndarray,
    clim_std: np.ndarray,
    f_dates: list[date],
) -> tuple[np.ndarray, np.ndarray]:
    """Достаёт норму на будущие даты из нормы, уже посчитанной на истории.

    Норма — функция дня года, поэтому ничего считать заново не нужно: для дня
    вперёд берётся значение того же дня года из истории. Если день года
    встречался в нескольких сезонах (норма в ядре считается с исключением
    текущего года и потому своя для каждого сезона), берётся самое позднее
    значение — оно построено по самой длинной истории.

    Дни года, которых в истории не было вовсе, добираются круговой
    интерполяцией по известным: разрыв в норме не должен рвать прогноз.
    """
    by_doy_mean: dict[int, float] = {}
    by_doy_std: dict[int, float] = {}
    # Идём по истории от старых дат к новым, поэтому поздние значения
    # естественным образом затирают ранние.
    for d, m, s in zip(dates, clim_mean, clim_std):
        if np.isfinite(m):
            doy = d.timetuple().tm_yday
            by_doy_mean[doy] = float(m)
            by_doy_std[doy] = float(s) if np.isfinite(s) else np.nan

    f_doys = np.array([d.timetuple().tm_yday for d in f_dates])
    if not by_doy_mean:
        nan = np.full(len(f_dates), np.nan)
        return nan, nan.copy()

    known = np.array(sorted(by_doy_mean))
    kmean = np.array([by_doy_mean[d] for d in known])
    kstd = np.array([by_doy_std[d] for d in known])

    # Круговая интерполяция: год замкнут, 31 декабря соседствует с 1 января.
    ext_x = np.concatenate([known - 366, known, known + 366])
    ext_m = np.concatenate([kmean, kmean, kmean])
    ext_s = np.concatenate([kstd, kstd, kstd])
    mean = np.interp(f_doys, ext_x, ext_m)
    std = np.interp(f_doys, ext_x, ext_s)

    # Разброс нормы не бывает меньше собственного шума наблюдения — та же
    # нижняя граница, что и в climatology.MIN_STD, продублирована здесь, чтобы
    # модуль не зависел от порядка импортов.
    std = np.where(np.isfinite(std) & (std > 0.05), std, 0.05)
    return mean, std


# На скольких первых днях горизонта оценивается «разболтанность» поля.
# Ограничение нужно из-за зимы: если горизонт дотягивается до ноября-декабря,
# норма там плоская и её разброс мал — и поле начинает выглядеть ПРЕДСКАЗУЕМЕЕ
# ровно потому, что прогноз забрался дальше. Это ложный сигнал: зимняя
# неподвижность индекса не означает, что мы стали лучше понимать поле.
SIGMA_SCALE_WINDOW_DAYS = 60


def _interval_sigma(k: np.ndarray, f_clim_std: np.ndarray) -> np.ndarray:
    """Ожидаемая ошибка прогноза на k дней вперёд для конкретного поля.

    Две составляющие: универсальный рост ошибки с горизонтом, замеренный на
    ретроспективе, и масштаб самого поля — разболтанные поля предсказываются
    вдвое хуже спокойных, и интервал обязан это показывать.

    Рост останавливается на SIGMA_SATURATION_DAYS: дальше прогноз равен норме,
    и его ошибка от горизонта уже не зависит.
    """
    k_eff = np.minimum(np.asarray(k, dtype=float), SIGMA_SATURATION_DAYS)
    base = SIGMA_A + SIGMA_B * np.sqrt(k_eff)
    head = np.asarray(f_clim_std)[:SIGMA_SCALE_WINDOW_DAYS]
    if np.isfinite(head).any():
        scale = float(np.nanmean(head)) / SIGMA_REF_STD
    else:
        # Нормы нет — считаем поле максимально непредсказуемым.
        scale = SIGMA_SCALE_MAX
    scale = float(np.clip(scale, SIGMA_SCALE_MIN, SIGMA_SCALE_MAX))
    return base * scale


def _risk_of(deviation: float) -> str:
    """Класс риска по ожидаемому отклонению от нормы (в долях)."""
    if deviation <= RISK_HIGH_DEVIATION:
        return RISK_HIGH
    if deviation <= RISK_MODERATE_DEVIATION:
        return RISK_MODERATE
    return RISK_LOW


def _confidence(
    *,
    n_days: int,
    f_clim_std: np.ndarray,
    have_norm: bool,
    stale_days: int,
    n_reference_years: int | None,
    clim_source: str,
    last_observation: date | None,
    anchor: date,
) -> float:
    """Насколько прогнозу можно верить, 0..1.

    Отправная точка — не мнение, а ожидаемая ошибка на конце горизонта: она уже
    посчитана для интервала. Доля отыгранного от «полного незнания» (0.30 NDVI)
    и есть базовая уверенность. Дальше её сбивают четыре обстоятельства, каждое
    из которых измерено или обосновано отдельно.
    """
    sigma_end = float(_interval_sigma(np.array([float(n_days)]), f_clim_std)[0])
    conf = 1.0 - sigma_end / CONFIDENCE_FULL_ERROR

    # 0. Плата за длинный горизонт. Ошибка после 25 дней расти перестаёт, но
    #    содержание прогноза — падает: к этому сроку от собственного состояния
    #    поля не остаётся ничего, и кривая целиком повторяет норму. Формально
    #    она так же точна, фактически это уже утверждение не о поле, а о
    #    культуре в среднем. В отличие от остальных множителей, этот замером не
    #    подкреплён — это осознанная осторожность, а не измеренная величина.
    conf /= 1.0 + 0.004 * max(n_days - SIGMA_SATURATION_DAYS, 0.0)

    # 1. Нормы нет — прогноз выродился в «останется как сейчас».
    if not have_norm:
        conf *= 0.35

    # 2. Норма по культуре, а не по самому полю: форма кривой чужая.
    if clim_source == "crop":
        conf *= CROP_NORM_CONFIDENCE

    # 3. Короткая история под нормой. Три сезона — нижняя граница, при которой
    #    норму вообще разрешено считать, восемь — уровень насыщения.
    if n_reference_years is not None:
        if n_reference_years < YEARS_MINIMAL:
            conf *= 0.5
        elif n_reference_years < YEARS_TRUSTED:
            conf *= 0.85

    # 4. Молчание съёмки. Считается от последнего РЕАЛЬНОГО снимка, если он
    #    известен: конец восстановленного ряда может быть уже экстраполяцией.
    silence = stale_days
    if last_observation is not None:
        silence = max(silence, (anchor - last_observation).days + stale_days)
    conf /= 1.0 + STALENESS_PENALTY_PER_DAY * max(silence, 0)

    return float(np.clip(conf, 0.05, 0.95))


def _percents(value: float) -> str:
    """«15 процентов», «22 процента», «21 процент» — согласование числительного.

    Мелочь, но фраза уходит агроному в интерфейс, и «на 44 процентов» сразу
    выдаёт, что текст собран программой и никем не вычитан.
    """
    n = int(round(value))
    tail100 = n % 100
    tail10 = n % 10
    if 11 <= tail100 <= 14:
        word = "процентов"
    elif tail10 == 1:
        word = "процент"
    elif tail10 in (2, 3, 4):
        word = "процента"
    else:
        word = "процентов"
    return f"{n} {word}"


def _date_phrase(d: date) -> str:
    """«К концу августа», «к середине сентября» — как сказал бы агроном."""
    part = "началу" if d.day <= 10 else ("середине" if d.day <= 20 else "концу")
    return f"К {part} {_MONTHS_GENITIVE[d.month - 1]}"


def _summary(
    end: date,
    *,
    deviation_mean: float,
    deviation_end: float,
    risk: str,
    confidence: float,
    have_norm: bool,
    stale_days: int,
    crop_type: str | None,
    clim_source: str,
) -> str:
    """Готовая фраза для интерфейса — для агронома, а не для инженера.

    Говорится ровно то, что модель умеет утверждать: насколько поле в среднем
    разойдётся с нормой за горизонт, чем это грозит и почему прогнозу стоит или
    не стоит верить. Проценты — от нормы, а не от абсолютного NDVI: «на 15
    процентов ниже нормы» агроному понятно, «на 0.07 NDVI» — нет.
    """
    if not have_norm:
        return (
            f"{_date_phrase(end)} прогноз даётся без климатической нормы — "
            "у поля нет своей истории, и сравнивать не с чем. "
            "Показано продолжение текущего уровня, доверять ему можно слабо."
        )

    pct = abs(deviation_mean) * 100.0
    if pct < 5:
        state = "поле останется около нормы"
    elif deviation_mean < 0:
        state = f"поле выйдет примерно на {_percents(pct)} ниже нормы"
    else:
        state = f"поле пойдёт примерно на {_percents(pct)} выше нормы"

    risk_phrase = {
        RISK_LOW: "Риск низкий.",
        RISK_MODERATE: "Риск умеренный: отставание устойчивое, но не критическое.",
        RISK_HIGH: "Риск высокий: отставание глубокое, к уборке недобор вероятен.",
    }[risk]

    parts = [f"{_date_phrase(end)} {state}. {risk_phrase}"]

    # Затухание — не деталь реализации, а содержательное утверждение о поле,
    # и агроному его нужно сказать вслух: разрыв к концу горизонта сходит на нет.
    if deviation_mean < RISK_MODERATE_DEVIATION and abs(deviation_end) < 0.05:
        parts.append(
            "Отставание набрано сейчас; к концу горизонта поле по прогнозу "
            "возвращается к норме, но потерянное за период уже не отыграется."
        )

    caveats = []
    if stale_days >= 10:
        caveats.append(f"свежих снимков нет уже {stale_days} дней")
    if clim_source == "crop":
        caveats.append(
            f"норма взята средняя по культуре ({crop_type})"
            if crop_type
            else "норма взята средняя по культуре"
        )
    if confidence < 0.35 and not caveats:
        caveats.append("исходных данных для уверенного прогноза мало")
    if caveats:
        parts.append("Прогноз ориентировочный: " + ", ".join(caveats) + ".")

    return " ".join(parts)
