def _season_rows(
    dates: list[date],
    restored: np.ndarray,
    clim_mean: np.ndarray,
    zscore: np.ndarray,
    anomalies: list,
) -> list[dict]:
    """Сырые числа по каждому сезону: интеграл, норма, стресс, длительность.

    Возвращает список словарей во внутреннем формате — с полями, которых нет в
    ответе наружу (покрытие, флаг полноты). Публичная таблица собирается из
    него отдельно.
    """
    if len(dates) == 0:
        return []

    years = np.array([d.year for d in dates])
    months = np.array([d.month for d in dates])
    in_season = (months >= SEASON_MONTHS[0]) & (months <= SEASON_MONTHS[1])

    # Дни, попадающие внутрь найденных периодов угнетения. Периоды приходят
    # готовыми из детектора, поэтому здесь не порог, а простое пересечение
    # интервалов с сеткой ряда: скоринг не должен заново решать, что считать
    # событием, — иначе таблица событий в интерфейсе и оценка риска разъедутся.
    event_weight = np.zeros(len(dates), dtype=float)
    for a in anomalies or []:
        try:
            start, end = a.start, a.end
            severity = getattr(a, "severity", "")
        except AttributeError:  # pragma: no cover - защита от чужого объекта
            continue
        mask = np.array([start <= d <= end for d in dates])
        # День внутри критического периода считается за два: шесть недель
        # угнетения ниже двух сигм — это другой по тяжести случай, чем шесть
        # недель ниже одной.
        w = 2.0 if severity == "critical" else 1.0
        event_weight = np.maximum(event_weight, mask * w)

    rows: list[dict] = []
    for year in sorted(set(int(y) for y in years[in_season])):
        m = in_season & (years == year)
        if not m.any():
            continue
        v = np.asarray(restored, dtype=float)[m]
        cm = np.asarray(clim_mean, dtype=float)[m] if clim_mean is not None else np.full(m.sum(), np.nan)
        z = np.asarray(zscore, dtype=float)[m] if zscore is not None else np.full(m.sum(), np.nan)

        ok = np.isfinite(v)
        n_days = int(ok.sum())
        coverage = n_days / SEASON_LENGTH_DAYS
        if n_days == 0:
            continue

        # Отрицательный NDVI — вода, снег или брак атмосферной коррекции.
        # В накопленную биомассу такие дни вносят ноль, а не отрицательный
        # вклад: биомасса не бывает отрицательной.
        v_pos = np.clip(v[ok], 0.0, None)
        # Интеграл приводится к полному сезону, иначе сезон с покрытием 80
        # процентов выглядит неурожайным просто из-за длины ряда.
        integral = float(v_pos.sum()) / n_days * SEASON_LENGTH_DAYS

        # Отклонение от нормы считается только по тем дням, где норма известна,
        # и по тем же дням берётся фактический ряд — так частичное покрытие
        # сокращается в отношении и не искажает результат.
        both = ok & np.isfinite(cm)
        if both.sum() >= 20:
            norm_int = float(np.clip(cm[both], 0.0, None).sum())
            fact_int = float(np.clip(v[both], 0.0, None).sum())
            vs_norm = fact_int / norm_int - 1.0 if norm_int > 0 else float("nan")
            # Абсолютный недобор биомассы: сколько NDVI-дней поле не добрало до
            # нормы. В отличие от z-оценки эта величина не делится на
            # собственный разброс поля и потому не «обнуляется» на нестабильных
            # полях. В балл не входит, но выводится в разбор сезона.
            shortfall = float(np.clip(cm[both] - v[both], 0.0, None).sum()) / norm_int
        else:
            vs_norm = float("nan")
            shortfall = float("nan")

        z_ok = z[np.isfinite(z)]
        stress_days = int((z_ok < Z_STRESS).sum())
        critical_days = int((z_ok < Z_CRITICAL).sum())
        worst_z = float(z_ok.min()) if z_ok.size else float("nan")
        event_days = float(event_weight[m][ok].sum())

        rows.append(
            {
                "year": year,
                "integral": integral,
                "vs_norm": vs_norm,
                "shortfall": shortfall,
                "stress_days": stress_days,
                "critical_days": critical_days,
                "worst_z": worst_z,
                "event_days": event_days,
                "coverage": coverage,
                "complete": coverage >= MIN_SEASON_COVERAGE,
            }
        )
    return rows


def _verdict(row: dict) -> str:
    """Короткая формулировка по сезону для таблицы в интерфейсе."""
    if not row["complete"]:
        return "сезон неполный, в расчёт не взят"
    vs = row["vs_norm"]
    if not np.isfinite(vs):
        return "нормы нет, сравнить не с чем"
    if vs >= 0.10:
        base = "выше нормы"
    elif vs >= -0.10:
        base = "в пределах нормы"
    elif vs >= -0.20:
        base = "недобор биомассы"
    else:
        base = "провальный сезон"
    if row["critical_days"] >= 10:
        base += ", критический эпизод"
    return base


