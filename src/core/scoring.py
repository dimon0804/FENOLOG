def _scale(value: float, xs: list[float], ys: list[float]) -> float:
    """Кусочно-линейный перевод физической величины в балл 0..100.

    Узлы xs могут идти как по возрастанию, так и по убыванию — второй случай
    разворачивается, потому что numpy.interp требует возрастающий порядок.
    За краями шкала не экстраполируется, а упирается в крайний балл: поле с
    разбросом 80 процентов не должно получать минус двести баллов.
    """
    if not np.isfinite(value):
        return float("nan")
    if xs[0] > xs[-1]:
        xs = xs[::-1]
        ys = ys[::-1]
    return float(np.interp(float(value), xs, ys))


def _theil_sen_slope(x: np.ndarray, y: np.ndarray) -> float:
    """Наклон по медиане попарных наклонов (оценка Тейла-Сена).

    Обычная регрессия наименьших квадратов на ряде из десяти сезонов
    разворачивается одним катастрофическим годом: засуха 2012-го способна
    нарисовать падающий тренд там, где его нет. Медиана попарных наклонов к
    одиночному выбросу нечувствительна, а на 5-15 точках считается мгновенно
    полным перебором пар.
    """
    n = len(x)
    if n < 3:
        return float("nan")
    slopes = []
    for i in range(n - 1):
        dx = x[i + 1:] - x[i]
        dy = y[i + 1:] - y[i]
        ok = dx != 0
        slopes.append(dy[ok] / dx[ok])
    all_slopes = np.concatenate(slopes) if slopes else np.array([])
    if all_slopes.size == 0:
        return float("nan")
    return float(np.median(all_slopes))


def _pct_ru(x: float) -> str:
    """Отклонение в долях -> человеческая формулировка «на 8 процентов выше».

    Деловой текст для страховой пишется словами, а не знаком процента: записку
    читает андеррайтер, а не фронтенд.
    """
    p = abs(x) * 100.0
    word = "выше" if x >= 0 else "ниже"
    return f"на {p:.0f} процент{_plural_pct(p)} {word}"


def _plural_pct(p: float) -> str:
    """Окончание слова «процент» по числу перед ним."""
    n = int(round(p))
    if 11 <= n % 100 <= 14:
        return "ов"
    last = n % 10
    if last == 1:
        return ""
    if last in (2, 3, 4):
        return "а"
    return "ов"


def _plural(n: int, one: str, few: str, many: str) -> str:
    """Выбор формы слова по числу: 1 стол, 2 стола, 5 столов."""
    if 11 <= n % 100 <= 14:
        return many
    last = n % 10
    if last == 1:
        return one
    if last in (2, 3, 4):
        return few
    return many


def _plural_season(n: int) -> str:
    """Окончание слова «сезон»."""
    if 11 <= n % 100 <= 14:
        return "ов"
    last = n % 10
    if last == 1:
        return ""
    if last in (2, 3, 4):
        return "а"
    return "ов"


def _grade(score: float) -> str:
    """Буквенная оценка по итоговому баллу."""
    for bound, letter in GRADE_BOUNDS:
        if score >= bound:
            return letter
    return "E"


