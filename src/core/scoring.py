def _stability_score(integrals: np.ndarray) -> tuple[float, float]:
    """Устойчивость урожайности год к году. Возвращает (балл, CV).

    Мера — коэффициент вариации сезонного интеграла. Именно эта величина стоит
    в основе тарифа страхования урожая: премия пропорциональна разбросу, а не
    среднему. Стандартное отклонение делится на среднее, потому что поля с
    разным уровнем NDVI надо сравнивать в одной шкале.
    """
    if integrals.size < 2:
        return float("nan"), float("nan")
    mean = float(integrals.mean())
    if mean <= 0:
        return float("nan"), float("nan")
    cv = float(integrals.std(ddof=1) / mean)
    return _scale(cv, STABILITY_CV, STABILITY_PTS), cv


def _stress_score(rows: list[dict], anomalies: list) -> tuple[float, dict]:
    """Стрессовая нагрузка: как часто, как глубоко и как долго поле проваливается.

    Пять измерителей, веса — по измеренной предсказательной силе (таблица
    рядом с константами STRESS_*):

      loss_freq    — доля сезонов с недобором больше 15 процентов от медианы
                     поля; эмпирическая частота страхового случая;
      worst_season — насколько глубоко поле провалилось в худший год;
      depth        — средний по сезонам минимум z-оценки, глубина ухода
                     внутри сезона;
      longest      — самый длинный непрерывный период угнетения за историю;
      days         — сколько дней за сезон ряд стоит ниже -1 сигмы.

    Первые два измерителя работают с СЕЗОННЫМ ИНТЕГРАЛОМ и потому нечувствительны
    к нормировке на собственную сигму поля; последний, наоборот, ею полностью
    съедается, и его вес минимален. Это не теоретическое соображение, а
    результат замера на разрыве 2010-2019 / 2020-2024.
    """
    use = [r for r in rows if r["complete"]]
    if not use:
        return float("nan"), {}

    # --- сезонные провалы, в долях от медианного сезона поля ----------------
    integrals = np.array([r["integral"] for r in use], dtype=float)
    median_int = float(np.median(integrals))
    if median_int > 0:
        rel = integrals / median_int - 1.0
        loss_freq = float((rel < -LOSS_SEASON_THRESHOLD).mean())
        worst_season = float(rel.min())
    else:
        loss_freq = float("nan")
        worst_season = float("nan")

    # --- глубина ухода и частота стрессовых дней внутри сезона --------------
    depths = [r["worst_z"] for r in use if np.isfinite(r["worst_z"])]
    depth = float(np.mean(depths)) if depths else float("nan")
    days = float(np.nanmean([r["stress_days"] for r in use]))

    # --- самый длинный непрерывный период угнетения -------------------------
    longest = max((int(getattr(a, "duration_days", 0)) for a in (anomalies or [])), default=0)

    parts = {
        "loss_freq": _scale(loss_freq, STRESS_LOSSFREQ, STRESS_LOSSFREQ_PTS),
        "worst_season": (
            _scale(abs(worst_season), STRESS_WORSTSEASON, STRESS_WORSTSEASON_PTS)
            if np.isfinite(worst_season) else float("nan")
        ),
        "depth": (
            _scale(abs(depth), STRESS_DEPTH, STRESS_DEPTH_PTS)
            if np.isfinite(depth) else float("nan")
        ),
        "longest": _scale(longest, STRESS_LONGEST, STRESS_LONGEST_PTS),
        "days": _scale(days, STRESS_DAYS, STRESS_DAYS_PTS),
    }
    # Если какая-то часть не посчиталась (например, нет z-оценки вовсе), её вес
    # перераспределяется на остальные, а не подменяется нулём: отсутствие
    # данных не то же самое, что плохое поле.
    total_w = sum(STRESS_MIX[k] for k, v in parts.items() if np.isfinite(v))
    if total_w == 0:
        return float("nan"), {}
    score = sum(STRESS_MIX[k] * v for k, v in parts.items() if np.isfinite(v)) / total_w
    detail = {
        "stress_days_per_season": days,
        "mean_worst_z": depth,
        "loss_season_share": loss_freq,
        "worst_season_shortfall": worst_season,
        "longest_suppression_days": longest,
    }
    return score, detail


def _productivity_score(
    integrals: np.ndarray, crop_type: str | None
) -> tuple[float, float, float]:
    """Уровень продуктивности относительно нормы своей культуры.

    Возвращает (балл, отношение к норме культуры, эталонный интеграл).

    Берётся медиана сезонных интегралов, а не среднее: у поля с одним
    провальным годом среднее уезжает вниз, но типичный уровень поля от этого не
    меняется — провал уже учтён в устойчивости и стрессе, второй раз его
    штрафовать нельзя.
    """
    if integrals.size == 0:
        return float("nan"), float("nan"), float("nan")
    ref = CROP_REFERENCE_INTEGRAL.get(crop_type or "", DEFAULT_REFERENCE_INTEGRAL)
    typical = float(np.median(integrals))
    ratio = typical / ref if ref > 0 else float("nan")
    return _scale(ratio, PRODUCTIVITY_RATIO, PRODUCTIVITY_PTS), ratio, ref


def _trend_score(years: np.ndarray, integrals: np.ndarray) -> tuple[float, float]:
    """Многолетний тренд накопленной биомассы. Возвращает (балл, наклон в долях/год).

    Наклон приводится к долям от среднего уровня, чтобы поля с разным уровнем
    NDVI сравнивались одинаково: минус два NDVI-дня в год на поле с интегралом
    140 и на поле с интегралом 60 — это разной тяжести деградация.

    Балл ужимается к нейтрали тем сильнее, чем короче история: наклон по трём
    точкам — это не тренд, а разница двух сезонов, и выдавать за него оценку
    риска нельзя.
    """
    if integrals.size < 3:
        return TREND_NEUTRAL, float("nan")
    mean = float(integrals.mean())
    if mean <= 0:
        return TREND_NEUTRAL, float("nan")
    slope = _theil_sen_slope(years.astype(float), integrals.astype(float)) / mean
    if not np.isfinite(slope):
        return TREND_NEUTRAL, float("nan")
    raw = _scale(slope, TREND_SLOPE, TREND_PTS)
    # Полное доверие наклону — от восьми сезонов и выше.
    shrink = float(np.clip((integrals.size - 2) / 6.0, 0.0, 1.0))
    return TREND_NEUTRAL + (raw - TREND_NEUTRAL) * shrink, slope


