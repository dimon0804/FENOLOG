def _summary(
    grade: str,
    score: int,
    n_seasons: int,
    cv: float,
    rows: list[dict],
    ratio: float,
    crop_type: str | None,
    slope: float,
    stress_detail: dict,
    confidence: float,
) -> str:
    """Две-три фразы для страховой. Деловой язык, без терминов из кода."""
    if n_seasons == 0:
        return (
            "Истории наблюдений не хватает даже на один полный сезон: оценить "
            "поле как объект риска нельзя."
        )

    # 1. Устойчивость и глубина провалов.
    if np.isfinite(cv):
        if cv <= 0.09:
            stab_word = "Поле стабильное"
        elif cv <= 0.15:
            stab_word = "Поле умеренно стабильное"
        elif cv <= 0.22:
            stab_word = "Поле неровное"
        else:
            stab_word = "Поле нестабильное"
        stab = f"{stab_word}: разброс накопленной биомассы между сезонами {cv * 100:.0f} процентов"
    else:
        stab = "Поле оценено по одному сезону, разброс между сезонами неизвестен"

    # Провал СЕЗОНА и критический эпизод ВНУТРИ сезона — разные вещи, и путать
    # их в записке для страховой нельзя. Первое — недобор урожая, то есть
    # страховой случай. Второе — глубокий уход z-оценки, который на стабильном
    # поле случается и в урожайный год просто потому, что у такого поля
    # маленькая сигма (см. разбор AOI-0030 в отчёте: z до -8 при интеграле
    # на 9 процентов ВЫШЕ нормы). Поэтому в тексте они идут отдельными
    # оборотами, а первым стоит именно недобор.
    complete = [r for r in rows if r["complete"]]
    deep = [r for r in complete if np.isfinite(r["vs_norm"]) and r["vs_norm"] <= -0.20]
    crit = [r for r in complete if r["critical_days"] >= 10]
    if deep:
        k = len(deep)
        loss = f"за {n_seasons} сезон{_plural_season(n_seasons)} {k} {_plural(k, 'провал', 'провала', 'провалов')}"
        worst = min(deep, key=lambda r: r["vs_norm"])
        loss += f", худший в {worst['year']} году ({_pct_ru(worst['vs_norm'])} нормы)"
    else:
        loss = (
            f"за {n_seasons} сезон{_plural_season(n_seasons)} ни одного провала "
            "глубже пятой части нормы"
        )
    if crit:
        m = len(crit)
        loss += (
            f"; при этом в {m} {_plural(m, 'сезоне', 'сезонах', 'сезонах')} были "
            f"затяжные уходы ниже двух сигм собственной нормы"
        )

    # 2. Уровень относительно культуры.
    if np.isfinite(ratio):
        crop_name = f"нормы по культуре «{crop_type}»" if crop_type else "усреднённой нормы"
        level = f"накопленная биомасса {_pct_ru(ratio - 1.0)} {crop_name}"
    else:
        level = "уровень продуктивности сравнить не с чем"

    # 3. Тренд, только если он заметен.
    trend = ""
    if np.isfinite(slope) and abs(slope) >= 0.01 and n_seasons >= 5:
        direction = "растёт" if slope > 0 else "снижается"
        trend = f" Многолетний тренд {direction} примерно на {abs(slope) * 100:.0f} процента в год."

    # 4. Вердикт по риску.
    risk = {
        "A": "Риск существенно ниже среднего",
        "B": "Риск ниже среднего",
        "C": "Риск средний",
        "D": "Риск выше среднего",
        "E": "Риск высокий",
    }[grade]
    if confidence < 0.55:
        risk += ", но достоверность оценки низкая — данных мало"

    return f"{stab}, {loss}, {level}.{trend} {risk} (балл {score}, класс {grade})."


