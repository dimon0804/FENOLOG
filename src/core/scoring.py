def _confidence(
    rows: list[dict],
    climatology_source: str,
    crop_type: str | None,
    observed: np.ndarray | None,
    dates: list[date],
) -> tuple[float, list[str]]:
    """Насколько оценке можно верить, 0..1, и список честных оговорок.

    Правило простое: оценка риска, выданная уверенным тоном на двух сезонах,
    хуже отсутствия оценки. Поэтому каждый дефект входных данных и понижает
    число, и обязан появиться словами в flags — андеррайтер должен видеть
    оговорку, а не только цифру.
    """
    flags: list[str] = []
    complete = [r for r in rows if r["complete"]]
    n = len(complete)

    # Длина истории — главный множитель.
    conf = float(np.interp(n, [0, 1, 2, 3, 5, 8, 12], [0.05, 0.20, 0.35, 0.55, 0.72, 0.85, 0.95]))
    if n < 3:
        flags.append(
            f"история короче трёх сезонов (полных сезонов: {n}) — оценка "
            "ориентировочная и не годится как основание для тарифа"
        )
    elif n < 5:
        flags.append(
            f"история {n} сезон{_plural_season(n)}: многолетний тренд "
            "статистически незначим, компонента тренда ужата к нейтрали"
        )

    # Источник климатической нормы.
    if climatology_source == "crop":
        conf *= 0.75
        flags.append(
            "норма взята средняя по типу культуры, а не по этому полю: "
            "глубина отклонений может быть как завышена, так и занижена"
        )
    elif climatology_source == "none":
        conf *= 0.45
        flags.append(
            "климатической нормы нет — стресс и продуктивность не рассчитаны, "
            "балл собран по неполному набору компонент"
        )

    # Покрытие сезонов.
    partial = [r for r in rows if not r["complete"]]
    if partial:
        flags.append(
            f"сезонов с покрытием ниже {int(MIN_SEASON_COVERAGE * 100)} процентов: "
            f"{len(partial)} — они показаны в таблице, но в расчёт балла не взяты"
        )

    # Плотность наблюдений, если вызывающая сторона её передала.
    if observed is not None and len(observed) == len(dates) and n > 0:
        months = np.array([d.month for d in dates])
        in_season = (months >= SEASON_MONTHS[0]) & (months <= SEASON_MONTHS[1])
        obs_arr = np.asarray(observed, dtype=bool)
        per_season = float(obs_arr[in_season].sum()) / max(n, 1)
        conf *= float(np.interp(per_season, [2, 5, 10, 18, 30], [0.45, 0.62, 0.80, 0.92, 1.0]))
        if per_season < 10:
            flags.append(
                f"снимков в среднем {per_season:.0f} за сезон — ряд восстановлен "
                "в основном интерполяцией, отдельные провалы могли быть сглажены"
            )

    if not crop_type:
        conf *= 0.90
        flags.append(
            "тип культуры не задан: уровень продуктивности сравнивается с "
            "усреднённой шкалой, а не с нормой конкретной культуры"
        )
    elif crop_type not in CROP_REFERENCE_INTEGRAL:
        conf *= 0.92
        flags.append(
            f"для культуры «{crop_type}» эталонного уровня нет — продуктивность "
            "оценена по усреднённой шкале"
        )

    # Две постоянные методические оговорки. Они не зависят от данных и должны
    # стоять в каждом отчёте, иначе число будет прочитано как измерение.
    flags.append(
        "интеграл NDVI — прокси накопленной биомассы, а не измеренная "
        "урожайность в центнерах с гектара"
    )
    flags.append(
        "порог z < -1 нормируется на собственную изменчивость поля: на "
        "стабильном поле его пробивает даже мелкое отклонение, на неровном — "
        "не пробивает крупное. Поэтому основной вес в оценке отдан недобору "
        "сезонного интеграла, а не числу дней ниже порога"
    )

    return float(np.clip(conf, 0.05, 0.98)), flags


