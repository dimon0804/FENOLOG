def field_score(
    dates: list[date],
    restored: np.ndarray,
    clim_mean: np.ndarray,
    clim_std: np.ndarray,
    zscore: np.ndarray,
    anomalies: list,
    crop_type: str | None = None,
    climatology_source: str = "polygon",
    observed: np.ndarray | None = None,
) -> dict:
    """Оценка поля как объекта риска.

    Аргументы повторяют то, что уже посчитало ядро: посуточная сетка дат,
    восстановленный ряд, климатическая норма и её разброс, z-оценка, найденные
    периоды угнетения (list[AnomalyPeriod] из src/contracts.py), тип культуры и
    источник нормы ("polygon" | "crop" | "none").

    Необязательный последний аргумент observed — булева маска «на этот день был
    реальный снимок». Он не входит в согласованный интерфейс и по умолчанию
    None; если его передать, достоверность оценки дополнительно учитывает
    плотность съёмки. Без него всё считается как раньше.

    Возвращает словарь:
      {
        "score": int,               # 0..100, чем выше тем надёжнее поле
        "grade": "A"|"B"|"C"|"D"|"E",
        "components": {"stability": int, "stress": int,
                       "productivity": int, "trend": int},
        "seasons": [{"year": int, "integral": float, "vs_norm": float,
                     "stress_days": int, "worst_z": float, "verdict": str}, ...],
        "yield_proxy": float,       # интеграл NDVI за последний полный сезон
        "yield_vs_norm": float,     # его отклонение от многолетней нормы, доли
        "stress_days_per_season": float,
        "confidence": float,        # 0..1
        "summary": str,             # деловая формулировка для страховой
        "flags": [str],             # честные оговорки
      }
    """
    dates = list(dates)
    restored = np.asarray(restored, dtype=float)
    clim_mean = np.asarray(clim_mean, dtype=float) if clim_mean is not None else np.full(len(dates), np.nan)
    zscore = np.asarray(zscore, dtype=float) if zscore is not None else np.full(len(dates), np.nan)

    rows = _season_rows(dates, restored, clim_mean, zscore, anomalies)
    complete = [r for r in rows if r["complete"]]

    confidence, flags = _confidence(rows, climatology_source, crop_type, observed, dates)

    # Публичная таблица по сезонам собирается всегда, даже когда балла нет:
    # андеррайтеру полезно видеть, что именно помешало посчитать оценку.
    seasons_out = [
        {
            "year": int(r["year"]),
            "integral": round(r["integral"], 1),
            "vs_norm": None if not np.isfinite(r["vs_norm"]) else round(r["vs_norm"], 3),
            "stress_days": int(r["stress_days"]),
            "worst_z": None if not np.isfinite(r["worst_z"]) else round(r["worst_z"], 2),
            "verdict": _verdict(r),
            # Полнота сезона отдаётся наружу, а не остаётся внутренней: без неё
            # потребитель таблицы вынужден догадываться, закрыт ли сезон, по
            # последней дате ряда — и ошибаться на текущем сезоне. Балл считается
            # только по полным сезонам, поэтому неполные надо помечать явно.
            "coverage": round(float(r["coverage"]), 3),
            "complete": bool(r["complete"]),
        }
        for r in rows
    ]

    if not complete:
        return {
            "score": 0,
            "grade": "E",
            "components": {"stability": 0, "stress": 0, "productivity": 0, "trend": 0},
            "seasons": seasons_out,
            "yield_proxy": float("nan"),
            "yield_vs_norm": float("nan"),
            "stress_days_per_season": float("nan"),
            "confidence": round(confidence, 2),
            "summary": _summary("E", 0, 0, float("nan"), rows, float("nan"),
                                crop_type, float("nan"), {}, confidence),
            "flags": flags,
        }

    integrals = np.array([r["integral"] for r in complete], dtype=float)
    years = np.array([r["year"] for r in complete], dtype=float)

    stability, cv = _stability_score(integrals)
    stress, stress_detail = _stress_score(rows, anomalies)
    productivity, ratio, _ref = _productivity_score(integrals, crop_type)
    trend, slope = _trend_score(years, integrals)

    parts = {
        "stability": stability,
        "stress": stress,
        "productivity": productivity,
        "trend": trend,
    }
    # Компоненту, которую не удалось посчитать, не заменяем нулём и не
    # заменяем средним: её вес перераспределяется между остальными, а причина
    # уже лежит в flags и снижает confidence.
    total_w = sum(WEIGHTS[k] for k, v in parts.items() if np.isfinite(v))
    raw = sum(WEIGHTS[k] * v for k, v in parts.items() if np.isfinite(v)) / total_w if total_w else 50.0

    # Усадка к середине при низкой достоверности. Смысл: на двух сезонах мы не
    # имеем права ни объявить поле отличным, ни объявить его провальным —
    # крайние оценки должны быть заработаны длиной истории. При полной
    # достоверности усадки нет.
    score = 50.0 + (raw - 50.0) * (0.55 + 0.45 * confidence)
    score = float(np.clip(score, 0.0, 100.0))
    grade = _grade(score)

    last = complete[-1]
    stress_per_season = stress_detail.get(
        "stress_days_per_season",
        float(np.mean([r["stress_days"] for r in complete])),
    )

    return {
        "score": int(round(score)),
        "grade": grade,
        "components": {
            k: (0 if not np.isfinite(v) else int(round(float(np.clip(v, 0, 100)))))
            for k, v in parts.items()
        },
        "seasons": seasons_out,
        "yield_proxy": round(float(last["integral"]), 1),
        "yield_vs_norm": (
            float("nan") if not np.isfinite(last["vs_norm"]) else round(float(last["vs_norm"]), 3)
        ),
        "stress_days_per_season": round(float(stress_per_season), 1),
        "confidence": round(float(confidence), 2),
        "summary": _summary(
            grade, int(round(score)), len(complete), cv, rows, ratio,
            crop_type, slope, stress_detail, confidence,
        ),
        "flags": flags,
    }
